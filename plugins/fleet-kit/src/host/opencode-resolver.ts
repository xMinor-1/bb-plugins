// The OpenCode 2 plugin that turns `{secret:name}` header templates into real
// header values at request time.
//
// Fleet Kit writes it to `<OpenCode config dir>/plugins/fleet-kit-secrets.js`,
// where OpenCode discovers it on start and when the file changes. For each
// provider it registers an `http.request` hook scoped to that provider, which
// sees the outgoing fetch Request. The headers are added only when the request
// goes to the origin of the provider's baseURL in the manifest: a project's
// opencode.json can override a provider's baseURL, and the key must not follow
// it there. A request that carries the key never follows a redirect either
// (`redirect: "error"`), so the key cannot ride a 3xx to another origin.
// Values come from the operating system's credential store (the same
// locations secret-store.ts writes), are cached for a minute and never logged.
// A wrong origin or a missing secret leaves the headers out and writes a
// warning, without the value, to `fleet-kit.log` in OpenCode's log directory
// (OpenCode 2.2.5 gives plugins no logger, and bb drops OpenCode's stderr);
// the provider answers 401.
import { createHash, randomUUID } from "node:crypto";
import { mkdir, open, readFile, rename, rm } from "node:fs/promises";
import { join } from "node:path";
import type { ResolverProvider } from "./opencode-config.js";
import { KEYCHAIN_SERVICE, WINDOWS_CREDENTIAL_SCRIPT, WINDOWS_TARGET_PREFIX, type SecretStore } from "../secret-store.js";

export const RESOLVER_FILE = "fleet-kit-secrets.js";
const MARKER = "// fleet-kit:opencode-secret-resolver";

export interface ResolverConfig {
  providers: Record<string, ResolverProvider>;
  store: SecretStore;
}

export function resolverSource(config: ResolverConfig): string {
  const settings = {
    providers: config.providers,
    store: {
      kind: config.store.kind,
      directory: config.store.directory,
      service: KEYCHAIN_SERVICE,
      targetPrefix: WINDOWS_TARGET_PREFIX,
    },
  };
  return `${MARKER}
// Generated by the Fleet Kit bb plugin. Fleet Kit rewrites or removes this file
// on every sync; edits here do not survive.
import { spawn } from "node:child_process";
import { appendFile, mkdir, readFile, stat, truncate } from "node:fs/promises";
import { homedir } from "node:os";
import { join } from "node:path";

const SETTINGS = ${JSON.stringify(settings, null, 2)};
const WINDOWS_SCRIPT = ${JSON.stringify(WINDOWS_CREDENTIAL_SCRIPT)};
const CACHE_MS = 60000;
// Reading Credential Manager starts PowerShell; retry a miss less often there.
const MISS_MS = SETTINGS.store.kind === "credential-manager" ? 30000 : 5000;
const cache = new Map();
const warned = new Map();

// Next to OpenCode's own opencode.log; read at call time so tests can move it.
function logDirectory() {
  return join(process.env.XDG_DATA_HOME || join(homedir(), ".local", "share"), "opencode", "log");
}

async function writeLog(message) {
  try {
    const directory = logDirectory();
    const file = join(directory, "fleet-kit.log");
    await mkdir(directory, { recursive: true });
    const size = await stat(file).then((info) => info.size, () => 0);
    if (size > 262144) await truncate(file, 0);
    await appendFile(file, "timestamp=" + new Date().toISOString() + " level=WARN service=fleet-kit message=" + JSON.stringify(message) + "\\n", { mode: 0o600 });
  } catch {
    // Logging must never break a model request.
  }
}

function warn(key, message) {
  const last = warned.get(key);
  if (last && Date.now() - last < 60000) return;
  warned.set(key, Date.now());
  console.warn("[fleet-kit] " + message);
  return writeLog(message);
}

function run(command, args, input, env) {
  return new Promise((resolve) => {
    let child;
    try {
      child = spawn(command, args, { env: env || process.env, stdio: ["pipe", "pipe", "ignore"], windowsHide: true, shell: false });
    } catch {
      resolve({ code: null, stdout: "" });
      return;
    }
    const chunks = [];
    let size = 0;
    const timer = setTimeout(() => child.kill("SIGKILL"), 30000);
    child.stdout.on("data", (chunk) => {
      size += chunk.length;
      if (size <= 65536) chunks.push(chunk);
    });
    child.on("error", () => {
      clearTimeout(timer);
      resolve({ code: null, stdout: "" });
    });
    child.on("close", (code) => {
      clearTimeout(timer);
      resolve({ code, stdout: Buffer.concat(chunks).toString("utf8") });
    });
    child.stdin.on("error", () => {});
    child.stdin.end(input || "");
  });
}

async function readStore(name) {
  const store = SETTINGS.store;
  if (store.kind === "file") {
    try {
      const value = (await readFile(join(store.directory, name), "utf8")).trim();
      return value === "" ? null : value;
    } catch {
      return null;
    }
  }
  if (store.kind === "keychain") {
    const result = await run("/usr/bin/security", ["find-generic-password", "-s", store.service, "-a", name, "-w"]);
    if (result.code !== 0) return null;
    const value = result.stdout.replace(/\\r?\\n$/, "");
    return value === "" ? null : value;
  }
  if (store.kind === "credential-manager") {
    const root = process.env.SystemRoot || "C:\\\\Windows";
    const powershell = join(root, "System32", "WindowsPowerShell", "v1.0", "powershell.exe");
    const env = { ...process.env, FLEET_KIT_SECRET_ACTION: "read", FLEET_KIT_SECRET_TARGET: store.targetPrefix + name };
    const result = await run(powershell, ["-NoProfile", "-NonInteractive", "-Command", "-"], WINDOWS_SCRIPT, env);
    return result.code === 0 && result.stdout !== "" ? result.stdout : null;
  }
  return null;
}

async function secret(name) {
  const hit = cache.get(name);
  const now = Date.now();
  if (hit && now - hit.at < (hit.value === null ? MISS_MS : CACHE_MS)) return hit.value;
  const value = await readStore(name);
  cache.set(name, { at: now, value });
  return value;
}

async function render(template) {
  let value = template;
  for (const match of template.matchAll(/\\{secret:([a-z0-9][a-z0-9-]*)\\}/g)) {
    const resolved = await secret(match[1]);
    if (resolved === null) return { missing: match[1] };
    value = value.split(match[0]).join(resolved);
  }
  return { value };
}

function originOf(url) {
  try {
    return new URL(url).origin;
  } catch {
    return null;
  }
}

async function addHeaders(providerID, event) {
  const provider = SETTINGS.providers[providerID];
  if (!provider) return;
  const origin = originOf(event.request.url);
  if (origin !== provider.origin) {
    await warn("origin:" + providerID, "not adding the build key for provider " + providerID + ": the request goes to " + origin + ", the build expects " + provider.origin);
    return;
  }
  const values = [];
  for (const { header, template } of provider.headers) {
    const rendered = await render(template);
    if (rendered.missing) {
      await warn("missing:" + rendered.missing, "the secret " + rendered.missing + " is not in the credential store; enter it in the Fleet Kit panel");
      return;
    }
    values.push([header, rendered.value]);
  }
  // Rebuild the request: a fetch Request's redirect mode cannot be changed in place.
  const headers = new Headers(event.request.headers);
  for (const [header, value] of values) headers.set(header, value);
  event.request = new Request(event.request, { headers, redirect: "error", duplex: "half" });
}

export default {
  id: "fleet-kit.secrets",
  async setup(ctx) {
    for (const providerID of Object.keys(SETTINGS.providers)) {
      await ctx.session.hook("http.request", (event) => addHeaders(providerID, event), { providerID });
    }
  },
};
`;
}

/** Write, replace or remove the resolver. Returns whether the file changed. */
export async function syncResolverPlugin(configDir: string, config: ResolverConfig | null): Promise<boolean> {
  const directory = join(configDir, "plugins");
  const target = join(directory, RESOLVER_FILE);
  let current: string | null = null;
  try {
    current = await readFile(target, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  if (current !== null && !current.startsWith(MARKER)) {
    throw new Error(`${target} exists and was not written by Fleet Kit; move it away`);
  }
  if (config === null || Object.keys(config.providers).length === 0) {
    if (current === null) return false;
    await rm(target);
    return true;
  }
  const next = resolverSource(config);
  if (current !== null && digest(current) === digest(next)) return false;
  await mkdir(directory, { recursive: true });
  const temporary = join(directory, `.${RESOLVER_FILE}.${randomUUID()}.tmp`);
  const handle = await open(temporary, "wx", 0o644);
  try {
    await handle.writeFile(next, "utf8");
    await handle.sync();
  } finally {
    await handle.close();
  }
  await rename(temporary, target);
  return true;
}

const digest = (text: string) => createHash("sha256").update(text).digest("hex");
