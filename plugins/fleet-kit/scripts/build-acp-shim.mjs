// The wrapper is one readable file (src/host/acp-shim.cjs); bb's plugin build bundles only code, so the server carries
// its text as a generated module. Run after changing the file; a test fails when they differ.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url);
const source = readFileSync(new URL("src/host/acp-shim.cjs", root), "utf8");
writeFileSync(
  new URL("src/host/acp-shim-source.ts", root),
  `// Generated by scripts/build-acp-shim.mjs from acp-shim.cjs. Do not edit.\nexport const ACP_SHIM_SOURCE = ${JSON.stringify(source)};\n`,
);
